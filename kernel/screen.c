#include "io.h"

#define WIDTH 320
#define HEIGHT 200
#define VGA_MEMORY ((unsigned char *)0xA0000)

// Простая палитра (первые 8 цветов)
void set_palette() {
    // Цвета: чёрный, белый, тёмно-синий, синий, серый, зелёный, красный, жёлтый
    unsigned char cols[8][3] = {
        {0,0,0}, {63,63,63}, {0,0,40}, {0,0,63},
        {32,32,32}, {0,63,0}, {63,0,0}, {63,63,0}
    };
    for (int i = 0; i < 8; i++) {
        outb(0x3C8, i);
        outb(0x3C9, cols[i][0]);
        outb(0x3C9, cols[i][1]);
        outb(0x3C9, cols[i][2]);
    }
}

void put_pixel(int x, int y, unsigned char color) {
    if (x >= 0 && x < WIDTH && y >= 0 && y < HEIGHT)
        VGA_MEMORY[y * WIDTH + x] = color;
}

void fill_rect(int x, int y, int w, int h, unsigned char color) {
    for (int j = 0; j < h; j++)
        for (int i = 0; i < w; i++)
            put_pixel(x + i, y + j, color);
}

// Простой шрифт 8x8 (только ASCII 32–127, для старта хватит)
